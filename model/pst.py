EVAL_TABLE = {
    Color.WHITE: {},
    Color.BLACK: {}
}

for piece_type in pieces:
    # Puste szachownice 8x8 dla obu kolorów
    EVAL_TABLE[Color.WHITE][piece_type] = [[0.0 for _ in range(8)] for _ in range(8)]
    EVAL_TABLE[Color.BLACK][piece_type] = [[0.0 for _ in range(8)] for _ in range(8)]

    pst = _BASE_PST[piece_type]

    for row in range(8):
        for col in range(8):
            white_pst_row = 7 - row
            EVAL_TABLE[Color.WHITE][piece_type][row][col] = pst[white_pst_row][col]

            black_pst_row = row
            EVAL_TABLE[Color.BLACK][piece_type][row][col] = -pst[black_pst_row][col]